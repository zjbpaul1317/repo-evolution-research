#!/usr/bin/env python3
"""Generate budget-derived assets from the config registry.

Run from any directory:

    .venv/bin/python scripts/gen_assets.py --write
    .venv/bin/python scripts/gen_assets.py --check

`--check` is the CI gate; it prints a unified diff for every stale asset.
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "skills/repo-evolution-research/scripts"))

from rer.config import (  # noqa: E402
    BUDGET_FIELDS,
    MODE_DEFAULTS,
    BudgetField,
    compute_config_hash,
)

ASSET_DIR = ROOT / "skills/repo-evolution-research/assets"
CONFIG_DEFAULT = ASSET_DIR / "config.default.json"
CONFIG_SCHEMA = ASSET_DIR / "schemas" / "config.schema.json"
MANIFEST_SCHEMA = ASSET_DIR / "schemas" / "manifest.schema.json"
CONFIGURATION_DOC = (
    ROOT / "skills/repo-evolution-research/references" / "configuration.md"
)
EXAMPLE_CONFIG = ROOT / "tests/fixtures/example/config.sample.json"
EXAMPLE_MANIFEST = ROOT / "tests/fixtures/example/manifest.sample.json"


def budget_defaults(fields: Sequence[BudgetField]) -> dict[str, int]:
    return {field.key: field.default for field in fields}


def budget_schema(fields: Sequence[BudgetField]) -> dict[str, Any]:
    return {
        "type": "object",
        "additionalProperties": False,
        "required": [field.key for field in fields if field.required],
        "properties": {
            field.key: {"type": "integer", "minimum": 1}
            for field in fields
        },
    }


def configuration_markdown(fields: Sequence[BudgetField]) -> str:
    lines = [
        "# Configuration Reference",
        "",
        "Generated by `scripts/gen_assets.py --write` from `rer.config.BUDGET_FIELDS`.",
        "Do not edit this file by hand.",
        "",
        "## Budget",
        "",
        "| Field | Standard default | Required | Source | Description |",
        "|---|---|---|---|---|",
    ]
    for field in fields:
        source = "mode default" if field.mode_derived else "registry"
        required = "yes" if field.required else "no"
        lines.append(
            f"| `{field.key}` | {field.default} | {required} | {source} | "
            f"{field.description} |"
        )

    mode_fields = [field for field in fields if field.mode_derived]
    lines.extend(["", "Mode-derived fields:", ""])
    headers = ["Mode", "Days", *(f"`{field.key}`" for field in mode_fields)]
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("|" + "---|" * len(headers))
    for mode, values in MODE_DEFAULTS.items():
        row = [mode, str(values["days"])]
        row.extend(str(values[field.key]) for field in mode_fields)
        lines.append("| " + " | ".join(row) + " |")

    optional = [field.key for field in fields if not field.required]
    if optional:
        joined = ", ".join(f"`{key}`" for key in optional)
        lines.extend(
            [
                "",
                f"Optional schema fields ({joined}) are not in `required`.",
                "Schema 1.2 removed `include_diff` and `max_diff_bytes_per_pr`;",
                "0.2.x resolved configs are incompatible and require a new init.",
            ]
        )
    lines.append("")
    return "\n".join(lines)


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _dump(document: Any) -> str:
    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def render(fields: Sequence[BudgetField] = BUDGET_FIELDS) -> dict[Path, str]:
    defaults = budget_defaults(fields)
    schema = budget_schema(fields)
    rendered: dict[Path, str] = {}

    config_default = _load(CONFIG_DEFAULT)
    config_default["budget"] = defaults
    rendered[CONFIG_DEFAULT] = _dump(config_default)

    for path in (CONFIG_SCHEMA, MANIFEST_SCHEMA):
        document = _load(path)
        document["$defs"]["budget"] = schema
        rendered[path] = _dump(document)

    example_config = _load(EXAMPLE_CONFIG)
    example_config["budget"] = defaults
    example_config["config_hash"] = compute_config_hash(example_config)
    rendered[EXAMPLE_CONFIG] = _dump(example_config)

    example_manifest = _load(EXAMPLE_MANIFEST)
    example_manifest["budget"] = defaults
    example_manifest["config_hash"] = example_config["config_hash"]
    rendered[EXAMPLE_MANIFEST] = _dump(example_manifest)

    rendered[CONFIGURATION_DOC] = configuration_markdown(fields)
    return rendered


def check(fields: Sequence[BudgetField] = BUDGET_FIELDS) -> list[str]:
    problems: list[str] = []
    for path, expected in render(fields).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current == expected:
            continue
        problems.extend(
            difflib.unified_diff(
                current.splitlines(),
                expected.splitlines(),
                fromfile=str(path.relative_to(ROOT)),
                tofile=f"{path.relative_to(ROOT)} (generated)",
                lineterm="",
            )
        )
    return problems


def write(fields: Sequence[BudgetField] = BUDGET_FIELDS) -> None:
    for path, content in render(fields).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--write", action="store_true", help="rewrite generated assets")
    action.add_argument(
        "--check",
        action="store_true",
        help="verify generated assets are current (default)",
    )
    args = parser.parse_args(argv)
    if args.write:
        write()
        return 0
    problems = check()
    if problems:
        print("\n".join(problems))
        return 1
    print("assets ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
